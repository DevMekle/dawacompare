// Bundles each serverless function in functions/ into one self-contained CommonJS file in api/.
// Vercel then runs api/*.js as-is: no TypeScript compile step and no runtime import resolution.
import { build } from "esbuild";

for (const name of ["catalogue", "identify"]) {
  await build({
    entryPoints: [`functions/${name}.ts`],
    outfile: `api/${name}.js`,
    bundle: true,
    platform: "node",
    target: "node18",
    format: "cjs",
    legalComments: "none",
    banner: { js: `// GENERATED by scripts/build-api.mjs from functions/${name}.ts. Do not edit; run \`npm run build:api\`.` },
    footer: { js: "module.exports = module.exports.default;" },
    logLevel: "warning",
  });
}
console.log("api/catalogue.js, api/identify.js bundled");
